import { test, expect } from "./fixtures";
import recording from "../fixtures/live-moussaka.json";
import { modelOutputSchema, normalizeRecipe, validateModelRecipe } from "../../src/lib/ai/recipe-schema";

// This is the actual Task 7.2 result, replayed locally; no provider traffic.
const query = "Рецепта за традиционна българска мусака за 4 порции";
const recipe = normalizeRecipe(validateModelRecipe(modelOutputSchema.parse(recording.output).recipe, query), recording.model);
for (const width of [1440, 375]) test(`recorded live moussaka works through all existing recipe components at ${width}px`, async ({ page, context, baseURL }, testInfo) => {
  await context.addCookies([{ name: "recipe-search-mode", value: "ai", url: baseURL! }]);
  await page.setViewportSize({ width, height: 900 });
  expect(recipe.id).toBe(recording.canonicalRecipeId);
  let calls = 0;
  await page.route("**/api/recipes/generate", async (route) => { calls++; expect(route.request().postDataJSON()).toEqual({ query }); await route.fulfill({ json: { recipe } }); });
  await page.goto("/");
  await page.getByRole("searchbox").fill(query);
  await page.getByRole("searchbox").press("Enter");
  await expect(page).toHaveURL(/\/search\?q=/);
  await expect(page.getByRole("article")).toContainText("4 порции");
  await page.getByRole("heading", { name: recipe.title, exact: true }).getByRole("link").click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(recipe.title);
  const potatoes = page.getByRole("checkbox", { name: /картофи/u });
  await expect(potatoes.locator("..")).toContainText("1000 г");
  await page.getByRole("button", { name: "Увеличи порциите" }).click({ clickCount: 2 });
  await expect(potatoes.locator("..")).toContainText("1500 г");
  await potatoes.check();
  await page.reload();
  await expect(potatoes).toBeChecked();
  await page.screenshot({ path: testInfo.outputPath(`live-recorded-details-${width}.png`), fullPage: true });
  await page.getByRole("link", { name: "Започни да готвиш" }).click();
  await expect(page.getByRole("heading", { level: 1 })).toContainText(recipe.title);
  if (width === 375) await page.getByRole("button", { name: "Продукти", exact: true }).click();
  await expect(potatoes).toBeChecked();
  await expect(potatoes.locator("..")).toContainText("1500 г");
  await page.getByRole("button", { name: "Старт на таймера" }).click();
  await page.getByRole("button", { name: /следваща/ }).click();
  await page.getByRole("button", { name: "Старт на таймера" }).click();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Приготвяне на месната смес", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Пауза на таймера" })).toBeEnabled();
  const stored = await page.evaluate((id) => JSON.parse(localStorage.getItem(`aichef:cooking:v1:${id}`)!), recipe.id);
  expect(stored.servings).toBe(6); expect(stored.checkedIngredients).toEqual(["ingredient-1"]);
  expect(stored.completedSteps).toEqual(["step-1"]); expect(stored.timers["step-1"].status).toBe("running");
  await page.getByRole("link", { name: "Изход" }).click();
  await expect(potatoes).toBeChecked();
  await expect(page.getByRole("group", { name: "Брой порции" })).toContainText("6 порции");
  await page.getByRole("link", { name: "Започни да готвиш" }).click();
  for (let index = 1; index < recipe.preparation!.steps.length - 1; index++) await page.getByRole("button", { name: /следваща/ }).click();
  await page.getByRole("button", { name: "Завърши готвенето" }).click();
  await expect(page.getByRole("heading", { name: "Браво! Ястието е готово!" })).toBeVisible();
  await expect(page.getByRole("heading", { level: 2 })).toHaveText(recipe.title);
  expect(calls).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
